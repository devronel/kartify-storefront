import type { Metadata } from "next";
import { Roboto, Roboto_Mono, Inter, Nunito_Sans } from "next/font/google";
import "./globals.css";
import { Toaster } from "@/components/ui/toast";
import { AuthProvider } from "@/context/AuthContext";
import { apiServer } from "@/lib/api-server";
import { ThemeProvider } from "@/components/theme-provider";
import { cn } from "@/lib/utils";

const nunitoSans = Nunito_Sans({subsets:['latin'],variable:'--font-sans'});

const roboto = Roboto({
  variable: "--font-roboto",
  subsets: ["latin"]
})

const robotoMono = Roboto_Mono({
  subsets: ["latin"],
  weight: ["400", "700"],
  variable: "--font-roboto-mono",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {

  let user = null

  try {

    const authUserResponse = await apiServer('/api/user')
    
    user = authUserResponse.data
  
  } catch (error) {
    
    user = null
  
  }

  return (
    <html lang="en" suppressHydrationWarning className={cn("h-full", "antialiased", roboto.variable, robotoMono.variable, "font-sans", nunitoSans.variable)}>
      <body className={`${roboto.className} min-h-full flex flex-col`}>
        <ThemeProvider
          attribute="class"
          defaultTheme="dark"
          enableSystem
          disableTransitionOnChange
        >
          <AuthProvider authUser={user}>
            {children}
            <Toaster />
          </AuthProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
